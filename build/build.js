'use strict';

// Bundles engine/*.js into apps-script/Engine.html so the browser can run the
// same engine code that the tests run in Node. Exposes window.WidaEngine.
// Usage: node build/build.js

const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const engineDir = path.join(root, 'engine');
const outFile = path.join(root, 'apps-script', 'Engine.html');

const files = fs.readdirSync(engineDir).filter((f) => f.endsWith('.js')).sort();

const modules = files.map((file) => {
  const source = fs.readFileSync(path.join(engineDir, file), 'utf8');
  const name = './' + file.replace(/\.js$/, '');
  return `  ${JSON.stringify(name)}: function (module, exports, require) {\n${source}\n  }`;
});

const bundle = `<!-- GENERATED by build/build.js from engine/. Do not edit by hand. -->
<script>
(function () {
  var definitions = {
${modules.join(',\n')}
  };
  var cache = {};
  function load(name) {
    if (cache[name]) return cache[name].exports;
    if (!definitions[name]) throw new Error('Engine module not found: ' + name);
    var module = { exports: {} };
    cache[name] = module;
    definitions[name](module, module.exports, load);
    return module.exports;
  }
  window.WidaEngine = load('./index');
})();
</script>
`;

fs.writeFileSync(outFile, bundle);
console.log(`Wrote ${path.relative(root, outFile)} from ${files.length} engine files: ${files.join(', ')}`);
